/**
 * Runs the full installation. Returns the admin user id. Throws on failure.
 */
function installer_run(array $db, array $admin, string $restaurant, bool $sample, string $appName = 'Saffron POS'): int
{
    @set_time_limit(900);
    $dsn = sprintf('mysql:host=%s;port=%d;charset=utf8mb4', $db['host'], (int)$db['port']);
    $pdo = new PDO($dsn, $db['user'], $db['pass'], [PDO::ATTR_ERRMODE => PDO::ERRMODE_EXCEPTION]);
    if (!preg_match('/^[A-Za-z0-9_]+$/', $db['name'])) {
        throw new InvalidArgumentException('Database name may only contain letters, numbers and underscores.');
    }
    $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$db['name']}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
    $pdo->exec("USE `{$db['name']}`");

    require_once APP_PATH . '/models/Backup.php';
    foreach (Backup::statements((string)file_get_contents(__DIR__ . '/schema.sql')) as $stmt) {
        $pdo->exec($stmt);
    }

    $ins = $pdo->prepare('INSERT INTO settings (`key`, `value`) VALUES (?, ?)');
    foreach (installer_default_settings($restaurant) as $k => $v) {
        $ins->execute([$k, $v]);
    }
    $cat = $pdo->prepare('INSERT INTO expense_categories (name, color) VALUES (?, ?)');
    foreach ([['Salaries & Wages', '#2563EB'], ['Rent', '#7C3AED'], ['Utilities', '#0891B2'], ['Raw Materials', '#16A34A'],
                 ['Packaging', '#CA8A04'], ['Maintenance & Repairs', '#DC2626'], ['Marketing', '#DB2777'], ['Transport & Fuel', '#EA580C'], ['Other', '#6B7280']] as $c) {
        $cat->execute($c);
    }
    $pdo->prepare('INSERT INTO users (name, username, email, password_hash, role) VALUES (?, ?, ?, ?, ?)')
        ->execute([$admin['name'], $admin['username'], $admin['email'] ?: null, password_hash($admin['password'], PASSWORD_DEFAULT), 'admin']);
    $adminId = (int)$pdo->lastInsertId();

    $config = [
        'db' => ['host' => $db['host'], 'port' => (int)$db['port'], 'name' => $db['name'], 'user' => $db['user'], 'pass' => $db['pass'], 'charset' => 'utf8mb4'],
        'app' => ['name' => $appName, 'debug' => false, 'session_name' => 'SAFFRONPOS', 'session_idle' => 7200],
    ];
    if (!is_dir(ROOT_PATH . '/config')) {
        mkdir(ROOT_PATH . '/config', 0755, true);
    }
    $written = file_put_contents(ROOT_PATH . '/config/config.php', "<?php\n// Generated by the installer on " . date('Y-m-d H:i') . "\nreturn " . var_export($config, true) . ";\n");
    if ($written === false) {
        throw new RuntimeException('Could not write config/config.php — check folder permissions.');
    }

    foreach (['uploads/products', 'uploads/logo', 'backups'] as $dir) {
        if (!is_dir(ROOT_PATH . "/$dir")) {
            mkdir(ROOT_PATH . "/$dir", 0755, true);
        }
    }

    installer_boot_app($config);
    if ($sample) {
        (new Seeder($adminId))->run();
    }
    $pdo->prepare("INSERT INTO audit_logs (user_id, action, entity, details, created_at) VALUES (?, 'system_installed', 'system', ?, ?)")
        ->execute([$adminId, $sample ? 'Installed with sample data' : 'Clean install', date('Y-m-d H:i:s')]);
    return $adminId;
}
